/* ------------------------------------------------------------------------- *
 * Drawing primitives. All operate on an RGBA8888 buffer (4 bytes/pixel,
 * row-major, R,G,B,A). All are bounds-checked: writes outside [0,W) x [0,H)
 * are silently skipped.
 * ------------------------------------------------------------------------- */

/* Write a single pixel. */
static inline void t8_putpx(uint8_t *rgba, int W, int H, int x, int y,
                            uint8_t r, uint8_t g, uint8_t b, uint8_t a) {
    if (rgba == NULL || x < 0 || y < 0 || x >= W || y >= H) {
        return;
    }
    size_t idx = ((size_t)y * (size_t)W + (size_t)x) * 4u;
    rgba[idx + 0u] = r;
    rgba[idx + 1u] = g;
    rgba[idx + 2u] = b;
    rgba[idx + 3u] = a;
}

/* Fill an axis-aligned rectangle. */
static inline void t8_fill_rect(uint8_t *rgba, int W, int H, int x, int y,
                                int w, int h, uint8_t r, uint8_t g,
                                uint8_t b, uint8_t a) {
    if (rgba == NULL || w <= 0 || h <= 0) {
        return;
    }
    int x0 = x;
    int y0 = y;
    int x1 = x + w; /* exclusive */
    int y1 = y + h; /* exclusive */
    if (x0 < 0) { x0 = 0; }
    if (y0 < 0) { y0 = 0; }
    if (x1 > W) { x1 = W; }
    if (y1 > H) { y1 = H; }
    for (int yy = y0; yy < y1; ++yy) {
        for (int xx = x0; xx < x1; ++xx) {
            size_t idx = ((size_t)yy * (size_t)W + (size_t)xx) * 4u;
            rgba[idx + 0u] = r;
            rgba[idx + 1u] = g;
            rgba[idx + 2u] = b;
            rgba[idx + 3u] = a;
        }
    }
}

/* Horizontal line of length `len` starting at (x, y), extending right. */
static inline void t8_hline(uint8_t *rgba, int W, int H, int x, int y,
                            int len, uint8_t r, uint8_t g, uint8_t b,
                            uint8_t a) {
    if (len <= 0) {
        return;
    }
    t8_fill_rect(rgba, W, H, x, y, len, 1, r, g, b, a);
}

/* Vertical line of length `len` starting at (x, y), extending down. */
static inline void t8_vline(uint8_t *rgba, int W, int H, int x, int y,
                            int len, uint8_t r, uint8_t g, uint8_t b,
                            uint8_t a) {
    if (len <= 0) {
        return;
    }
    t8_fill_rect(rgba, W, H, x, y, 1, len, r, g, b, a);
}

/* Draw one glyph at (x, y), each font pixel scaled to `scale` x `scale`. */
static inline void t8_char(uint8_t *rgba, int W, int H, int x, int y,
                           char c, int scale, uint8_t r, uint8_t g,
                           uint8_t b, uint8_t a) {
    if (scale < 1) {
        scale = 1;
    }
    unsigned int uc = (unsigned int)(unsigned char)c;
    if (uc >= 128u) {
        return; /* outside table; nothing to draw */
    }
    const unsigned char *glyph = FONT8X8_BASIC[uc];
    for (int row = 0; row < 8; ++row) {
        unsigned char bits = glyph[row];
        if (bits == 0u) {
            continue;
        }
        for (int col = 0; col < 8; ++col) {
            if (bits & (unsigned char)(1u << col)) { /* bit 0 = leftmost */
                t8_fill_rect(rgba, W, H,
                             x + col * scale, y + row * scale,
                             scale, scale, r, g, b, a);
            }
        }
    }
}

/* Draw a string left-to-right with 8*scale advance per char.
 * Non-printable chars (< 0x20 or > 0x7E) advance without drawing.
 * Returns the end x coordinate (start x + advance for all chars). */
static inline int t8_text(uint8_t *rgba, int W, int H, int x, int y,
                          const char *s, int scale, uint8_t r, uint8_t g,
                          uint8_t b, uint8_t a) {
    if (scale < 1) {
        scale = 1;
    }
    int cx = x;
    if (s == NULL) {
        return cx;
    }
    size_t n = strlen(s);
    for (size_t i = 0; i < n; ++i) {
        unsigned char ch = (unsigned char)s[i];
        if (ch >= 0x20u && ch <= 0x7Eu) {
            t8_char(rgba, W, H, cx, y, (char)ch, scale, r, g, b, a);
        }
        cx += 8 * scale;
    }
    return cx;
}

/* Pixel width of a string when drawn at the given scale (for alignment). */
static inline int t8_text_w(const char *s, int scale) {
    if (scale < 1) {
        scale = 1;
    }
    if (s == NULL) {
        return 0;
    }
    size_t n = strlen(s);
    return (int)n * 8 * scale;
}

